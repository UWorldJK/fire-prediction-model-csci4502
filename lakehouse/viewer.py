def render_html(data: ViewerData) -> str:
    years = f"{data.study_years.start}–{data.study_years.stop - 1}"
    silver = ("<ul>" + "".join(f"<li><code>{escape(t)}</code></li>" for t in data.silver_tables) + "</ul>"
              if data.silver_tables else '<p class="meta">None yet. The cleaning stage writes these with <code>write_silver</code>.</p>')
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>Fire Lakehouse Contents</title>
<style>{CSS}</style></head><body><main>
<h1>Fire lakehouse contents</h1>
<p class="meta">s3://{escape(data.bucket)} · {escape(data.region)} · study years {years} · generated {escape(data.generated_at)} · commit {escape(data.git_sha[:8])}</p>
{_cards(data)}
<h2>gridMET (daily weather, 4 km)</h2>{_gridmet_matrix(data)}
<h2>MTBS fires per year</h2>{_mtbs_chart(data.mtbs_counts)}
<h2>LANDFIRE (terrain, fuels, fire regime)</h2>{_landfire(data)}
<h2>Silver tables</h2>{silver}
<h2>Lineage</h2>{_lineage(data)}
<h2>How to load</h2><pre><code>{escape(HOW_TO)}</code></pre>
</main><script>{FILTER_JS}</script></body></html>"""


# ---------------- publish / open ----------------

def publish_viewer() -> str:
    html = render_html(collect_viewer_data())
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "index.html"
        path.write_text(html, encoding="utf-8")
        s3.upload_file(path, VIEWER_KEY, content_type="text/html; charset=utf-8")
    return VIEWER_KEY


def main() -> None:
    path = s3.download_file(VIEWER_KEY, refresh=True)
    print(f"Opening {path}")
    webbrowser.open(path.as_uri())


if __name__ == "__main__":
    main()
