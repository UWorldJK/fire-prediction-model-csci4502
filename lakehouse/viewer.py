def _cards(data: ViewerData) -> str:
    by_source: dict[str, list[ManifestRecord]] = {}
    for rec in data.manifests:
        by_source.setdefault(rec.source, []).append(rec)
    cards = []
    for source in sorted(by_source):
        recs = by_source[source]
        gb = sum(r.bytes for r in recs) / 1e9
        last = max(r.downloaded_at for r in recs)
        cards.append(
            f'<div class="card"><span>{escape(source)}</span><b>{len(recs)} files</b>'
            f"<span>{gb:.2f} GB · last {escape(last[:10])}</span></div>"
        )
    return '<div class="cards">' + "".join(cards or ['<div class="card"><b>empty</b><span>no manifests yet</span></div>']) + "</div>"


def _gridmet_matrix(data: ViewerData) -> str:
    years = list(range(data.study_years.start - 1, data.study_years.stop))
    head = "".join(f"<th>{str(y)[2:]}</th>" for y in years)
    rows = []
    for var in config.GRIDMET_VARS:
        lo, hi = data.gridmet_integrated.get(var, (None, None))
        cells = []
        for y in years:
            if (var, y) in data.gridmet_raw:
                cls = "raw integrated" if lo is not None and lo <= y <= hi else "raw"
            else:
                cls = "missing"
            cells.append(f'<td data-cell="{var}-{y}" class="{cls}" title="{var} {y}: {cls}"></td>')
        rows.append(f"<tr><th>{var}</th>{''.join(cells)}</tr>")
    legend = ('<div class="legend"><span><i style="background:var(--raw)"></i>raw file</span>'
              '<span><i style="background:var(--int)"></i>raw + in integrated Zarr</span>'
              '<span><i style="background:var(--miss)"></i>missing</span></div>')
    return f'{legend}<div class="scroll"><table class="matrix"><tr><th></th>{head}</tr>{"".join(rows)}</table></div>'


def _mtbs_chart(counts: pd.DataFrame) -> str:
    if counts.empty:
        return "<p class=meta>No MTBS data yet.</p>"
    colors = {"Wildfire": "var(--wild)", "Prescribed Fire": "var(--rx)"}
    years = list(counts.index)
    totals = counts.sum(axis=1)
    peak = max(int(totals.max()), 1)
    w, h, pad = 900, 220, 28
    bw = (w - pad) / len(years)
    bars = []
    for i, year in enumerate(years):
        y0 = h - 20
        for col in counts.columns:
            n = int(counts.loc[year, col])
            if not n:
                continue
            bh = n / peak * (h - 40)
            y0 -= bh
            bars.append(
                f'<rect x="{pad + i * bw + 1:.1f}" y="{y0:.1f}" width="{max(bw - 2, 1):.1f}" height="{bh:.1f}" '
                f'fill="{colors.get(col, "var(--other)")}"><title>{year} {escape(str(col))}: {n}</title></rect>'
            )
        if len(years) <= 30 or i % 2 == 0:
            bars.append(f'<text x="{pad + i * bw + bw / 2:.1f}" y="{h - 5}" text-anchor="middle">{str(year)[2:]}</text>')
    bars.append(f'<text x="0" y="14">{peak}</text>')
    legend = "".join(
        f'<span><i style="background:{colors.get(c, "var(--other)")}"></i>{escape(str(c))} ({int(counts[c].sum())})</span>'
        for c in counts.columns
    )
    return (f'<div class="legend">{legend}</div><div class="scroll"><svg viewBox="0 0 {w} {h}" width="100%" '
            f'role="img" aria-label="MTBS fires per year">{"".join(bars)}</svg></div>'
            f'<p class="meta">{int(totals.sum())} fires total, {years[0]}–{years[-1]}.</p>')


def _landfire(data: ViewerData) -> str:
    tiles = config.make_tiles(config.WEST_BBOX, config.LANDFIRE_TILE_DEG)
    groups = list(config.LANDFIRE_GROUPS)
    west, south, east, north = config.WEST_BBOX
    scale = 20
    w, h = (east - west) * scale, (north - south) * scale
    rects = []
    for tile_id, (tw, ts, te, tn) in tiles:
        n = sum((g, tile_id) in data.landfire_tiles for g in groups)
        opacity = 0.12 + 0.88 * n / len(groups)
        rects.append(
            f'<rect x="{(tw - west) * scale:.0f}" y="{(north - tn) * scale:.0f}" width="{(te - tw) * scale:.0f}" '
            f'height="{(tn - ts) * scale:.0f}" fill="var(--int)" fill-opacity="{opacity:.2f}" stroke="var(--panel)">'
            f"<title>{tile_id}: {n}/{len(groups)} groups</title></rect>"
            f'<text x="{(tw - west) * scale + 4:.0f}" y="{(north - tn) * scale + 14:.0f}">{tile_id}</text>'
        )
    svg = (f'<svg viewBox="0 0 {w:.0f} {h:.0f}" width="100%" style="max-width:420px" role="img" '
           f'aria-label="LANDFIRE tile coverage">{"".join(rects)}</svg>')
    head = "".join(f"<th>{t}</th>" for t, _ in tiles)
    rows = []
    for g in groups:
        cells = "".join(
            f'<td data-tile="{g}-{t}" class="{"integrated" if (g, t) in data.landfire_tiles else "missing"}" title="{g} {t}"></td>'
            for t, _ in tiles
        )
        rows.append(f"<tr><th>{g}</th>{cells}</tr>")
    layer_rows = "".join(
        f"<tr><td>{g}</td><td>{name}</td><td>{'mosaic ready' if name in data.landfire_integrated else '—'}</td></tr>"
        for g, names in config.LANDFIRE_GROUPS.items() for name in names
    )
    return (f'<p class="meta">Tile map (darker = more layer groups downloaded):</p>{svg}'
            f'<div class="scroll"><table class="matrix"><tr><th></th>{head}</tr>{"".join(rows)}</table></div>'
            f'<div class="scroll" style="margin-top:12px"><table class="lineage"><tr><th>group</th><th>layer</th>'
            f"<th>integrated COG</th></tr>{layer_rows}</table></div>")


def _lineage(data: ViewerData) -> str:
    rows = "".join(
        f"<tr><td>{escape(r.source)}</td><td><code>{escape(r.s3_key)}</code></td><td>{r.bytes / 1e6:,.1f} MB</td>"
        f"<td>{escape(r.downloaded_at)}</td><td><code>{escape(r.sha256[:12])}</code></td>"
        f"<td>{escape(r.source_url)}</td><td><code>{escape(r.git_sha[:8])}</code></td></tr>"
        for r in sorted(data.manifests, key=lambda r: r.downloaded_at, reverse=True)
    )
    return ('<input type="search" id="q" placeholder="Filter by source, key, URL…" aria-label="Filter lineage">'
            '<div class="scroll"><table class="lineage" id="lineage"><tr><th>source</th><th>S3 key</th><th>size</th>'
            f"<th>downloaded</th><th>sha256</th><th>source</th><th>commit</th></tr>{rows}</table></div>")


