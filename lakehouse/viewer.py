VIEWER_KEY = "viewer/index.html"


@dataclass
class ViewerData:
    bucket: str
    region: str
    study_years: range
    generated_at: str
    git_sha: str
    manifests: list[ManifestRecord]
    gridmet_raw: set[tuple[str, int]]
    gridmet_integrated: dict[str, tuple[int, int]]
    mtbs_counts: pd.DataFrame  # index: year, columns: incid_type
    landfire_tiles: set[tuple[str, str]]
    landfire_integrated: set[str]
    silver_tables: list[str] = field(default_factory=list)


# ---------------- collect ----------------

def _gridmet_integrated(manifests: list[ManifestRecord]) -> dict[str, tuple[int, int]]:
    out: dict[str, tuple[int, int]] = {}
    for rec in sorted(manifests, key=lambda r: r.downloaded_at):
        if rec.source == "integrated_gridmet":
            params = json.loads(rec.params)
            out[params["variable"]] = tuple(params["years"])
    return out


def _mtbs_counts() -> pd.DataFrame:
    from lakehouse.read import read_mtbs  # local import keeps module import light

    if s3.object_exists(config.INTEGRATED_MTBS_KEY):
        fires = read_mtbs()
    else:
        snaps = [k for k in s3.list_keys("bronze/mtbs/") if k.endswith(".parquet")]
        if not snaps:
            return pd.DataFrame()
        fires = read_mtbs(re.search(r"snapshot=([^/]+)/", snaps[-1]).group(1))
    year = pd.to_datetime(fires["ig_date"], errors="coerce").dt.year
    return pd.crosstab(year, fires["incid_type"]).sort_index()


def collect_viewer_data() -> ViewerData:
    """Inventory from S3 listings and manifests only (no Athena spend)."""
    manifests = read_manifests()
    gridmet_raw = set()
    for key in s3.list_keys("bronze/gridmet/"):
        m = re.search(r"variable=([^/]+)/year=(\d{4})/", key)
        if m:
            gridmet_raw.add((m.group(1), int(m.group(2))))
    tiles = set()
    for key in s3.list_keys("bronze/landfire/"):
        m = re.search(r"group=([^/]+)/tile=([^/]+)/[^/]+\.tif$", key)
        if m:
            tiles.add((m.group(1), m.group(2)))
    integrated_lf = {Path(k).stem for k in s3.list_keys("bronze/integrated/landfire/") if k.endswith(".tif")}
    silver = sorted({f"silver_{k.split('/')[1].removesuffix('.zarr')}" for k in s3.list_keys("silver/") if k.count("/") >= 2})
    return ViewerData(
        bucket=config.bucket(), region=config.REGION, study_years=config.study_years(),
        generated_at=utc_now(), git_sha=git_sha(), manifests=manifests, gridmet_raw=gridmet_raw,
        gridmet_integrated=_gridmet_integrated(manifests), mtbs_counts=_mtbs_counts(),
        landfire_tiles=tiles, landfire_integrated=integrated_lf, silver_tables=silver,
    )


